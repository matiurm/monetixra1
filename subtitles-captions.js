/**
 * Subtitles and Captions System for Monetixra
 * Multi-language subtitle support with auto-generation
 */

const SubtitlesCaptions = (function() {
  'use strict';

  // Storage
  let videoSubtitles = new Map();
  let subtitleTracks = new Map();

  /**
   * Create subtitle track
   * @param {Object} trackData - Track data
   * @returns {Object} Created track
   */
  function createSubtitleTrack(trackData) {
    const trackId = generateId();

    const track = {
      id: trackId,
      videoId: trackData.videoId,
      language: trackData.language || 'en',
      languageName: trackData.languageName || 'English',
      label: trackData.label || 'Track 1',
      isAutoGenerated: trackData.isAutoGenerated || false,
      createdAt: Date.now()
    };

    subtitleTracks.set(trackId, track);
    return track;
  }

  /**
   * Add subtitle to track
   * @param {string} trackId - Track ID
   * @param {Object} subtitleData - Subtitle data
   * @returns {Object} Created subtitle
   */
  function addSubtitle(trackId, subtitleData) {
    const subtitles = videoSubtitles.get(trackId) || [];
    const subtitleId = generateId();

    const subtitle = {
      id: subtitleId,
      trackId,
      startTime: subtitleData.startTime || 0,
      endTime: subtitleData.endTime || 0,
      text: subtitleData.text || '',
      position: subtitleData.position || 'bottom',
      style: subtitleData.style || {},
      createdAt: Date.now()
    };

    subtitles.push(subtitle);
    subtitles.sort((a, b) => a.startTime - b.startTime);
    videoSubtitles.set(trackId, subtitles);

    return subtitle;
  }

  /**
   * Get subtitle tracks for video
   * @param {string} videoId - Video ID
   * @returns {Array} Tracks
   */
  function getSubtitleTracks(videoId) {
    const allTracks = Array.from(subtitleTracks.values());
    return allTracks.filter(track => track.videoId === videoId);
  }

  /**
   * Get subtitles for track
   * @param {string} trackId - Track ID
   * @returns {Array} Subtitles
   */
  function getSubtitles(trackId) {
    return videoSubtitles.get(trackId) || [];
  }

  /**
   * Get subtitle at timestamp
   * @param {string} trackId - Track ID
   * @param {number} timestamp - Timestamp in seconds
   * @returns {Object} Subtitle
   */
  function getSubtitleAtTimestamp(trackId, timestamp) {
    const subtitles = videoSubtitles.get(trackId) || [];
    return subtitles.find(sub => timestamp >= sub.startTime && timestamp <= sub.endTime) || null;
  }

  /**
   * Update subtitle
   * @param {string} trackId - Track ID
   * @param {string} subtitleId - Subtitle ID
   * @param {Object} updates - Updates to apply
   * @returns {Object} Updated subtitle
   */
  function updateSubtitle(trackId, subtitleId, updates) {
    const subtitles = videoSubtitles.get(trackId) || [];
    const subtitle = subtitles.find(sub => sub.id === subtitleId);

    if (subtitle) {
      Object.assign(subtitle, updates);
      videoSubtitles.set(trackId, subtitles);
      return subtitle;
    }

    return null;
  }

  /**
   * Delete subtitle
   * @param {string} trackId - Track ID
   * @param {string} subtitleId - Subtitle ID
   * @returns {Object} Result
   */
  function deleteSubtitle(trackId, subtitleId) {
    const subtitles = videoSubtitles.get(trackId) || [];
    const index = subtitles.findIndex(sub => sub.id === subtitleId);

    if (index > -1) {
      subtitles.splice(index, 1);
      videoSubtitles.set(trackId, subtitles);
      return { success: true, message: 'Subtitle deleted' };
    }

    return { success: false, message: 'Subtitle not found' };
  }

  /**
   * Delete subtitle track
   * @param {string} trackId - Track ID
   * @returns {Object} Result
   */
  function deleteSubtitleTrack(trackId) {
    subtitleTracks.delete(trackId);
    videoSubtitles.delete(trackId);
    return { success: true, message: 'Track deleted' };
  }

  /**
   * Export subtitles to SRT format
   * @param {string} trackId - Track ID
   * @returns {string} SRT format
   */
  function exportToSRT(trackId) {
    const subtitles = videoSubtitles.get(trackId) || [];
    const track = subtitleTracks.get(trackId);

    let srt = '';
    let index = 1;

    subtitles.forEach(sub => {
      const startTime = formatSRTTime(sub.startTime);
      const endTime = formatSRTTime(sub.endTime);

      srt += `${index}\n`;
      srt += `${startTime} --> ${endTime}\n`;
      srt += `${sub.text}\n\n`;

      index++;
    });

    return srt;
  }

  /**
   * Import subtitles from SRT format
   * @param {string} videoId - Video ID
   * @param {string} language - Language code
   * @param {string} srtContent - SRT content
   * @returns {Object} Result
   */
  function importFromSRT(videoId, language, srtContent) {
    try {
      const track = createSubtitleTrack({
        videoId,
        language,
        languageName: getLanguageName(language),
        isAutoGenerated: false
      });

      const lines = srtContent.split('\n');
      let currentIndex = 0;
      let startTime, endTime, text;

      for (let i = 0; i < lines.length; i++) {
        const line = lines[i].trim();

        if (line.match(/^\d+$/)) {
          // Index line
          currentIndex = parseInt(line);
        } else if (line.includes('-->')) {
          // Time line
          const times = line.split('-->');
          startTime = parseSRTTime(times[0].trim());
          endTime = parseSRTTime(times[1].trim());
        } else if (line !== '' && !line.match(/^\d+$/) && !line.includes('-->')) {
          // Text line
          text = line;

          if (startTime !== undefined && endTime !== undefined && text !== undefined) {
            addSubtitle(track.id, {
              startTime,
              endTime,
              text
            });
          }

          startTime = undefined;
          endTime = undefined;
          text = undefined;
        }
      }

      return { success: true, trackId: track.id };
    } catch (error) {
      return { success: false, message: 'Failed to import SRT' };
    }
  }

  /**
   * Format time to SRT format
   * @param {number} seconds - Time in seconds
   * @returns {string} Formatted time
   */
  function formatSRTTime(seconds) {
    const hours = Math.floor(seconds / 3600);
    const minutes = Math.floor((seconds % 3600) / 60);
    const secs = Math.floor(seconds % 60);
    const ms = Math.floor((seconds % 1) * 1000);

    return `${pad(hours)}:${pad(minutes)}:${pad(secs)},${pad(ms, 3)}`;
  }

  /**
   * Parse SRT time format
   * @param {string} timeStr - Time string
   * @returns {number} Time in seconds
   */
  function parseSRTTime(timeStr) {
    const [time, ms] = timeStr.split(',');
    const [hours, minutes, secs] = time.split(':');

    return (
      parseInt(hours) * 3600 +
      parseInt(minutes) * 60 +
      parseInt(secs) +
      parseInt(ms) / 1000
    );
  }

  /**
   * Pad number with zeros
   * @param {number} num - Number
   * @param {number} length - Length
   * @returns {string} Padded string
   */
  function pad(num, length = 2) {
    return num.toString().padStart(length, '0');
  }

  /**
   * Get language name from code
   * @param {string} code - Language code
   * @returns {string} Language name
   */
  function getLanguageName(code) {
    const languages = {
      'en': 'English',
      'es': 'Spanish',
      'fr': 'French',
      'de': 'German',
      'it': 'Italian',
      'pt': 'Portuguese',
      'ru': 'Russian',
      'ja': 'Japanese',
      'ko': 'Korean',
      'zh': 'Chinese',
      'ar': 'Arabic',
      'hi': 'Hindi',
      'bn': 'Bengali'
    };

    return languages[code] || code;
  }

  /**
   * Generate unique ID
   * @returns {string} Unique ID
   */
  function generateId() {
    return `${Date.now()}_${Math.random().toString(36).substr(2, 9)}`;
  }

  // Initialize
  function initialize() {
    console.log('[SubtitlesCaptions] Module initialized');
  }

  initialize();

  return {
    createSubtitleTrack,
    addSubtitle,
    getSubtitleTracks,
    getSubtitles,
    getSubtitleAtTimestamp,
    updateSubtitle,
    deleteSubtitle,
    deleteSubtitleTrack,
    exportToSRT,
    importFromSRT
  };
})();

// Export for use in other modules
if (typeof module !== 'undefined' && module.exports) {
  module.exports = SubtitlesCaptions;
}
